package io.github.miuzarte.littlewhale.voice

/**
 * 那几句"说给手机听"的命令
 *
 * 主人 2026-10-05 定的两级设计: 短唤醒词只做"有人在叫我", **紧随其后的那一句交给常驻 ASR**,
 * 由文本里解析意图 —— 这一份就是"解析"那一头应用侧写出去的那两句。
 *
 * **词表只有一份, 在宿主插件里** (`host-plugin/index.mjs` 的 `VOICE_COMMANDS`): 那里才是认识这两句
 * 的人, 改词表也是改那一个数组 (可行性稿 2.7: 改 host 侧一张表就行, 不必重下关键词表、也不必重建
 * APK)。应用这一侧只把这些句子**写进收件箱**, 由插件那条投递链去认 —— 所以浮标菜单里点「视频模式」
 * 与张嘴说"打开视频模式"走的是同一条路, 不会有两份实现
 *
 * 为什么这几句要留在 Kotlin 里而不是也读插件那份: 菜单与「叫醒之后」那个开关在应用这一侧就要
 * 写下一句确定的话 (不能拼字符串, 也不能猜)。两份不许漂, 所以有 `tools/check-voice-commands.mjs`
 * 拿这两份源码对着核 (与词表那两份实现同一个办法)
 */
internal object VoiceCommands {

    /** 切到视频模式: 提示词换成视频那份 + 常驻语音许可靠上 + 摄像头起来 */
    const val VIDEO = "打开视频模式"

    /** 切回手机模式: 收工那条 (摄像头还回去, 常驻语音那个许可收回) */
    const val PHONE = "回到手机模式"

    /**
     * 打断: **浮标"正在想"那一档双击写出去的就是这一句** (主人 2026-10-06)
     *
     * 它与那两句模式命令是同一类东西 (整句相等、由插件那张表认、不进会话), 只是落在插件那张表的
     * `interrupt` 那一支上: 那一支做的事是"取消浮标那一场正在跑的轮 + 把球上那三个字落下"
     * (范围见 host-plugin 的 `runVoiceInterrupt`)
     *
     * 为什么不新开一条桥: 应用 → 宿主只有 [VoiceInbox] 这一条门 (理由写在它的文件头), 而"正在想"是
     * 宿主推来的状态 —— 要停它只能请宿主去做
     *
     * 它**也认说出来的那一句**: 命令词表只有一份, 张嘴说"打断当前回答"与双击球走的是同一条
     */
    const val INTERRUPT = "打断当前回答"

    /**
     * 这几句都要能被插件认出来, 顺序与插件那张表一致
     *
     * **识屏那两句不在这里了** (批次 4): 那个模式整个摘掉了, 而"退出识屏模式 / 关闭识屏模式 / 关掉
     * 识屏模式"这三句兼容说法留在插件那张表的 `phone` 那一支里 —— 应用这一侧没有哪一处会写它们 (写
     * 它们的那一行菜单已经删了), 所以这里不列; `tools/check-voice-commands.mjs` 那一头单独核"那几句
     * 兼容说法还在不在"
     */
    val ALL = listOf(VIDEO, PHONE, INTERRUPT)
}
